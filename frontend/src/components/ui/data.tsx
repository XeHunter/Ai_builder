/** Page chrome and data-display primitives: headers, stat cards, provenance badges, pagination. */
import { ChevronLeft, ChevronRight, type LucideIcon } from "lucide-react";
import * as React from "react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Tooltip } from "@/components/ui/menu";
import { cn } from "@/lib/utils";

export function PageHeader({ title, description, actions, eyebrow }: { title: string; description?: React.ReactNode; actions?: React.ReactNode; eyebrow?: React.ReactNode }) {
  return (
    <div className="mb-6 flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
      <div>
        {eyebrow && <div className="mb-1 text-xs font-medium uppercase tracking-wide text-primary">{eyebrow}</div>}
        <h1 className="text-2xl font-semibold">{title}</h1>
        {description && <p className="mt-1 max-w-3xl text-sm text-muted-foreground">{description}</p>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </div>
  );
}

interface StatCardProps {
  label: string;
  value: React.ReactNode;
  hint?: React.ReactNode;
  icon?: LucideIcon;
  tone?: "default" | "danger" | "warning" | "success";
  onClick?: () => void;
}

export function StatCard({ label, value, hint, icon: Icon, tone = "default", onClick }: StatCardProps) {
  const toneCls = { default: "text-primary bg-primary-soft", danger: "text-danger bg-danger-soft", warning: "text-warning bg-warning-soft", success: "text-success bg-success-soft" }[tone];
  const Comp = onClick ? "button" : "div";
  return (
    <Comp
      onClick={onClick}
      className={cn(
        "flex w-full items-start justify-between gap-3 rounded-lg border border-border bg-surface p-4 text-left shadow-[var(--shadow-card)]",
        onClick && "transition hover:border-primary/40 hover:shadow-md",
      )}
    >
      <div className="min-w-0">
        <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">{label}</p>
        <p className="tabular mt-1 text-2xl font-semibold">{value}</p>
        {hint && <p className="mt-1 text-xs text-muted-foreground">{hint}</p>}
      </div>
      {Icon && (
        <div className={cn("rounded-md p-2", toneCls)}>
          <Icon className="size-4" aria-hidden />
        </div>
      )}
    </Comp>
  );
}

const PROVENANCE: Record<string, { label: string; variant: "accent" | "info" | "warning" | "primary" | "neutral"; text: string }> = {
  simulated: { label: "Simulated data", variant: "accent", text: "Generated by a deterministic simulator, not a live integration." },
  demo: { label: "Demo data", variant: "accent", text: "Seeded synthetic demo data." },
  rule: { label: "Business rule", variant: "neutral", text: "Deterministic, configurable rule." },
  heuristic: { label: "Heuristic", variant: "warning", text: "Explicit heuristic with stated assumptions - not a learned model." },
  statistical: { label: "Statistical model", variant: "info", text: "Statistical method computed from your transaction data." },
  ml: { label: "ML model", variant: "primary", text: "Machine-learning model (scikit-learn) trained on your data." },
  llm: { label: "LLM", variant: "primary", text: "Generated by a large language model and validated against store data." },
  deterministic: { label: "Deterministic AI fallback", variant: "neutral", text: "Rule-based demo provider (no AI API key configured)." },
};

/** Labels how a number or recommendation was produced. Use on every analytics surface. */
export function Provenance({ kind, className, detail }: { kind: keyof typeof PROVENANCE | string; className?: string; detail?: string }) {
  const p = PROVENANCE[kind] ?? { label: kind, variant: "neutral" as const, text: "" };
  return (
    <Tooltip content={detail ?? p.text}>
      <span tabIndex={0}>
        <Badge variant={p.variant} className={cn("cursor-help", className)}>
          {p.label}
        </Badge>
      </span>
    </Tooltip>
  );
}

export function Pagination({ page, pageSize, total, onPage }: { page: number; pageSize: number; total: number; onPage: (p: number) => void }) {
  const pages = Math.max(1, Math.ceil(total / pageSize));
  return (
    <div className="flex items-center justify-between gap-3 px-1 py-3 text-sm text-muted-foreground">
      <span className="tabular">
        {total === 0 ? "No results" : `${(page - 1) * pageSize + 1}–${Math.min(page * pageSize, total)} of ${total}`}
      </span>
      <div className="flex items-center gap-1">
        <Button variant="outline" size="icon" aria-label="Previous page" disabled={page <= 1} onClick={() => onPage(page - 1)}>
          <ChevronLeft />
        </Button>
        <span className="tabular px-2">
          {page} / {pages}
        </span>
        <Button variant="outline" size="icon" aria-label="Next page" disabled={page >= pages} onClick={() => onPage(page + 1)}>
          <ChevronRight />
        </Button>
      </div>
    </div>
  );
}

export function KeyValue({ items, className }: { items: [string, React.ReactNode][]; className?: string }) {
  return (
    <dl className={cn("grid grid-cols-[auto_1fr] gap-x-4 gap-y-1.5 text-sm", className)}>
      {items.map(([k, v]) => (
        <React.Fragment key={k}>
          <dt className="text-muted-foreground">{k}</dt>
          <dd className="tabular min-w-0 break-words font-medium">{v}</dd>
        </React.Fragment>
      ))}
    </dl>
  );
}
