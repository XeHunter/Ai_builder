"""Generate reference documentation from the code (keeps docs aligned with the implementation).

    python -m app.docs_gen

Writes:
* docs/api/openapi.json        - the FastAPI OpenAPI specification
* docs/api/endpoints.md        - endpoint table grouped by tag
* docs/architecture/er-diagram.md - Mermaid ER diagram of every table, PK/FK and relationship
"""

from __future__ import annotations

import json
from collections import defaultdict

from app.core.config import REPO_DIR


def write_openapi() -> int:
    from app.main import app

    spec = app.openapi()
    out = REPO_DIR / "docs" / "api"
    out.mkdir(parents=True, exist_ok=True)
    (out / "openapi.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")
    by_tag: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            tag = (op.get("tags") or ["other"])[0]
            summary = (op.get("summary") or "").strip()
            desc = (op.get("description") or "").strip().split("\n")[0]
            by_tag[tag].append((method.upper(), path, desc or summary))
    lines = [
        "# API endpoints",
        "",
        "_Generated by `python -m app.docs_gen` from the FastAPI OpenAPI spec. Do not edit by hand._",
        "",
        "Base URL: `/api/v1`. Interactive docs: `http://localhost:8000/docs` (Swagger UI) and `/redoc`.",
        "WebSocket: `GET /api/v1/ws/shopping-lists/{list_id}` (see TECHNICAL_README §F).",
        "",
    ]
    total = 0
    for tag in sorted(by_tag):
        lines += [f"## {tag}", "", "| Method | Path | Description |", "|---|---|---|"]
        for method, path, desc in sorted(by_tag[tag], key=lambda r: (r[1], r[0])):
            lines.append(f"| {method} | `{path}` | {desc.replace('|', '/')} |")
            total += 1
        lines.append("")
    (out / "endpoints.md").write_text("\n".join(lines), encoding="utf-8")
    return total


def write_er_diagram() -> int:
    import app.db.models  # noqa: F401
    from app.db.base import Base

    lines = ["# Entity-relationship diagram", "",
             "_Generated by `python -m app.docs_gen` from the SQLAlchemy models. Do not edit by hand._", "",
             "```mermaid", "erDiagram"]
    rels = []
    for table in sorted(Base.metadata.tables.values(), key=lambda t: t.name):
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            typ = col.type.__class__.__name__.lower().replace("utcdatetime", "timestamptz")
            key = "PK" if col.primary_key else ("FK" if col.foreign_keys else "")
            lines.append(f"        {typ} {col.name}{(' ' + key) if key else ''}")
        lines.append("    }")
        for fk in table.foreign_keys:
            target = fk.column.table.name
            if target != table.name:
                rels.append(f"    {target} ||--o{{ {table.name} : \"{fk.parent.name}\"")
    lines += sorted(set(rels))
    lines.append("```")
    out = REPO_DIR / "docs" / "architecture"
    out.mkdir(parents=True, exist_ok=True)
    (out / "er-diagram.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(Base.metadata.tables)


if __name__ == "__main__":
    n = write_openapi()
    t = write_er_diagram()
    print(f"Wrote {n} endpoints and an ER diagram of {t} tables.")
