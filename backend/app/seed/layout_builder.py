"""Builds the sample supermarket floor plan (40 m x 30 m) with fixtures, walkable graph and shelves.

Coordinates are metres, x to the right and y downwards (SVG convention).

    y=0   ┌──────────────── back wall: Dairy & Eggs chillers (D) ───────────────┐
    y=3   │ B0 ─ B1 ─ ... back walkway ... ─ B6 ─ B7                             │
          │ P  |A1|  |A2|  |A3|  |A4|  |A5|  |A6|                     F (frozen) │
    y=5-20│ (produce/bakery wall)  aisles with shelf faces L/R, 4 sections         │
    y=21  │      E1    E2    E3    E4    E5   (endcaps facing the front walkway)   │
    y=22  │ F0 ─ F1 ─ FE1 ─ F2 ─ ... front walkway ...                ─ F7       │
    y=25  │ ENT              CLR (clearance)          checkouts C1-C3   EXIT      │
    y=30  └──────────────────────────────────────────────────────────────────────┘
"""

from __future__ import annotations

import math
import uuid

from sqlalchemy.orm import Session

from app.db.models import LayoutFixture, NavEdge, NavNode, ShelfLocation, StoreLayout

AISLE_X = [7.0, 12.0, 17.0, 22.0, 27.0, 32.0]
SECTION_Y = [6.9, 10.6, 14.4, 18.1]
FRONT_Y, BACK_Y = 22.0, 3.0
LEFT_X, RIGHT_X = 2.8, 36.5
LEVEL_HEIGHT_CM = {1: 20, 2: 60, 3: 100, 4: 140, 5: 180}


def build_standard_layout(db: Session, store_id: uuid.UUID, name: str = "Main floor v1", created_by_id: uuid.UUID | None = None) -> tuple[StoreLayout, dict[str, ShelfLocation]]:
    layout = StoreLayout(store_id=store_id, name=name, version=1, status="active", width_m=40.0, height_m=30.0,
                         created_by_id=created_by_id, notes="Sample floor plan generated by the demo seed.")
    db.add(layout)
    db.flush()

    nodes: dict[str, NavNode] = {}

    def node(code: str, x: float, y: float, kind: str = "walkway", label: str | None = None) -> NavNode:
        n = NavNode(layout_id=layout.id, code=code, x=x, y=y, kind=kind, label=label)
        db.add(n)
        nodes[code] = n
        return n

    edges: list[tuple[str, str, bool]] = []

    def edge(a: str, b: str, accessible: bool = True) -> None:
        edges.append((a, b, accessible))

    # Front walkway chain (aisle mouths + endcap access points)
    front_codes: list[str] = []
    node("F0", LEFT_X, FRONT_Y, label="the front walkway")
    front_codes.append("F0")
    for i, x in enumerate(AISLE_X, start=1):
        node(f"F{i}", x, FRONT_Y, label=f"Aisle {i}")
        front_codes.append(f"F{i}")
        if i < len(AISLE_X):
            node(f"FE{i}", x + 2.5, FRONT_Y, label="the front walkway")
            front_codes.append(f"FE{i}")
    node("F7", RIGHT_X, FRONT_Y, label="the front walkway")
    front_codes.append("F7")
    for a, b in zip(front_codes, front_codes[1:], strict=False):
        edge(a, b)

    # Back walkway
    back_codes = ["B0"]
    node("B0", LEFT_X, BACK_Y, label="the back walkway")
    for i, x in enumerate(AISLE_X, start=1):
        node(f"B{i}", x, BACK_Y, label=f"Aisle {i}")
        back_codes.append(f"B{i}")
    node("B7", RIGHT_X, BACK_Y, label="the back walkway")
    back_codes.append("B7")
    for a, b in zip(back_codes, back_codes[1:], strict=False):
        edge(a, b)

    # Aisles
    for i, x in enumerate(AISLE_X, start=1):
        prev = f"B{i}"
        for s, y in enumerate(SECTION_Y, start=1):
            code = f"A{i}-{s}"
            node(code, x, y, label=f"Aisle {i}")
            edge(prev, code)
            prev = code
        edge(prev, f"F{i}")

    # Perimeter walkways
    prev_l, prev_r = "B0", "B7"
    for s, y in enumerate([8.0, 13.0, 18.0], start=1):
        node(f"L{s}", LEFT_X, y, label="the produce & bakery wall")
        node(f"R{s}", RIGHT_X, y, label="the frozen wall")
        edge(prev_l, f"L{s}")
        edge(prev_r, f"R{s}")
        prev_l, prev_r = f"L{s}", f"R{s}"
    edge(prev_l, "F0")
    edge(prev_r, "F7")

    # Entrance, clearance point, checkout and exit
    node("ENT", 3.5, 27.5, kind="entrance", label="the entrance")
    node("CLRN", 20.0, 24.5, label="the clearance bin")
    node("CHK", 31.0, 24.5, kind="checkout", label="the checkouts")
    node("EXIT", 37.0, 27.5, kind="exit", label="the exit")
    edge("ENT", "F0")
    edge("ENT", "F1")
    edge("CLRN", "F4")
    edge("CLRN", "FE3")
    edge("CHK", "F6")
    edge("CHK", "FE5")
    edge("CHK", "F7")
    edge("CHK", "EXIT")
    db.flush()
    for a, b, acc in edges:
        na, nb = nodes[a], nodes[b]
        db.add(NavEdge(layout_id=layout.id, from_node_id=na.id, to_node_id=nb.id,
                       distance_m=round(math.hypot(na.x - nb.x, na.y - nb.y), 2), is_accessible=acc))

    # Fixtures & shelf locations
    shelves: dict[str, ShelfLocation] = {}

    def fixture(code: str, kind: str, label: str, x: float, y: float, w: float, h: float, levels: int = 1,
                aisle: str | None = None, chilled: bool = False, movable: bool = False, props: dict | None = None) -> LayoutFixture:
        f = LayoutFixture(layout_id=layout.id, code=code, kind=kind, label=label, x=x, y=y, width=w, height=h,
                          levels=levels, aisle_code=aisle, is_chilled=chilled, is_movable=movable, properties=props or {})
        db.add(f)
        return f

    def shelf(f: LayoutFixture, code: str, aisle: str | None, section: int, level: int, x: float, y: float,
              access: str, clearance: bool = False, capacity: int = 6) -> None:
        sl = ShelfLocation(layout_id=layout.id, fixture=f, code=code, aisle_code=aisle, section=section, level=level,
                           height_cm=LEVEL_HEIGHT_CM.get(level, 60), x=x, y=y, capacity_facings=capacity,
                           access_node_id=nodes[access].id, is_clearance=clearance)
        db.add(sl)
        shelves[code] = sl

    for i, x in enumerate(AISLE_X, start=1):
        aisle = f"A{i}"
        for side, fx in (("L", x - 2.0), ("R", x + 1.2)):
            f = fixture(f"{aisle}-{side}", "aisle_shelf", f"Aisle {i} {'left' if side == 'L' else 'right'}",
                        fx, 5.0, 0.8, 15.0, levels=5, aisle=aisle)
            for s, y in enumerate(SECTION_Y, start=1):
                for lvl in range(1, 6):
                    shelf(f, f"{aisle}-{side}-{s}-{lvl}", aisle, s, lvl, fx + 0.4, y, f"{aisle}-{s}")

    dairy = fixture("D", "chiller", "Dairy & eggs chillers", 6.0, 0.4, 28.0, 1.0, levels=4, chilled=True)
    for s in range(1, 8):
        cx = 6.0 + (s - 0.5) * 4.0
        access = min(back_codes, key=lambda c: abs(nodes[c].x - cx))
        for lvl in range(1, 5):
            shelf(dairy, f"D-{s}-{lvl}", "D", s, lvl, cx, 0.9, access, capacity=8)

    produce = fixture("P", "wall_shelf", "Produce & bakery wall", 0.4, 5.0, 1.0, 15.0, levels=3)
    for s, y in enumerate([8.0, 13.0, 18.0], start=1):
        for lvl in range(1, 4):
            shelf(produce, f"P-{s}-{lvl}", "P", s, lvl, 0.9, y, f"L{s}", capacity=8)

    frozen = fixture("Z", "freezer", "Frozen foods", 38.6, 5.0, 1.0, 15.0, levels=3, chilled=True)
    for s, y in enumerate([8.0, 13.0, 18.0], start=1):
        for lvl in range(1, 4):
            shelf(frozen, f"Z-{s}-{lvl}", "Z", s, lvl, 39.1, y, f"R{s}")

    for k in range(1, 6):
        gx = AISLE_X[k - 1] + 1.2
        f = fixture(f"E{k}", "endcap", f"Endcap {k}", gx, 20.4, 2.6, 0.8, levels=3, movable=True)
        for lvl in range(1, 4):
            shelf(f, f"E{k}-1-{lvl}", f"E{k}", 1, lvl, gx + 1.3, 20.8, f"FE{k}", capacity=4)

    clr = fixture("CLR", "clearance", "Clearance bin", 18.8, 23.6, 2.4, 1.2, levels=1, movable=True)
    shelf(clr, "CLR-1-1", "CLR", 1, 1, 20.0, 24.2, "CLRN", clearance=True, capacity=12)

    for c in range(1, 4):
        fixture(f"C{c}", "checkout", f"Checkout {c}", 28.0 + (c - 1) * 2.6, 25.5, 1.6, 2.2)
    fixture("ENTR", "entrance", "Entrance", 1.5, 28.6, 4.0, 1.2)
    fixture("EXT", "exit", "Exit", 35.0, 28.6, 4.0, 1.2)
    db.flush()
    return layout, shelves
